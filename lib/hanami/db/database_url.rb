# frozen_string_literal: true

require "uri"

module Hanami
  module DB
    # Helpers for inspecting database URLs, including the JDBC URLs required when connecting via
    # JRuby, which nest the real URL after a "jdbc:" prefix, e.g. "jdbc:postgresql://localhost/app".
    #
    # Shared by hanami and hanami-cli so that both recognise the same databases.
    #
    # @api private
    # @since 3.1.0
    module DatabaseURL
      # Prefix of the JDBC URLs that JRuby applications must use
      #
      # @api private
      # @since 3.1.0
      JDBC_PREFIX = "jdbc:"

      # Maps URL schemes to the database adapters we support
      #
      # @api private
      # @since 3.1.0
      ADAPTERS = {
        "sqlite" => :sqlite,
        "postgres" => :postgres,
        "postgresql" => :postgres,
        "mysql" => :mysql,
        "mysql2" => :mysql
      }.freeze

      # Gems required to connect via each URL scheme. Only schemes generated by `hanami new` are
      # included: others (such as Sequel's "mysql" scheme, which uses the mysql gem rather than
      # mysql2) are left alone.
      #
      # @api private
      # @since 3.1.0
      NATIVE_GEMS = {
        "sqlite" => "sqlite3",
        "postgres" => "pg",
        "postgresql" => "pg",
        "mysql2" => "mysql2"
      }.freeze

      # Gems required to connect via each JDBC subprotocol
      #
      # @api private
      # @since 3.1.0
      JDBC_GEMS = {
        "sqlite" => "jdbc-sqlite3",
        "postgresql" => "jdbc-postgres",
        "mysql" => "jdbc-mysql"
      }.freeze

      # Adapters for each JDBC subprotocol. JDBC drivers accept only these subprotocols, e.g.
      # "postgresql" but not "postgres".
      #
      # @api private
      # @since 3.1.0
      JDBC_ADAPTERS = ADAPTERS.slice(*JDBC_GEMS.keys).freeze

      module_function

      # Returns true if the URL is a JDBC URL.
      #
      # @param url [String, #to_s]
      #
      # @return [Boolean]
      #
      # @api private
      # @since 3.1.0
      def jdbc?(url)
        url.to_s.start_with?(JDBC_PREFIX)
      end

      # Returns the URL parsed as a URI, with any JDBC prefix removed.
      #
      # @param url [String, #to_s]
      #
      # @return [URI::Generic]
      #
      # @raise [URI::InvalidURIError] if the URL cannot be parsed
      #
      # @api private
      # @since 3.1.0
      def uri(url)
        URI(url.to_s.delete_prefix(JDBC_PREFIX))
      end

      # Returns the adapter for the URL, or nil if it is not one we support.
      #
      # @example
      #   DatabaseURL.adapter("postgresql://localhost/app") # => :postgres
      #   DatabaseURL.adapter("jdbc:sqlite:db/app.sqlite3") # => :sqlite
      #
      # @param url [String, #to_s]
      #
      # @return [Symbol, nil] :sqlite, :postgres or :mysql
      #
      # @api private
      # @since 3.1.0
      def adapter(url)
        adapters = jdbc?(url) ? JDBC_ADAPTERS : ADAPTERS
        adapters[uri(url).scheme]
      rescue URI::Error
        nil
      end

      # Returns the name of the gem required to connect to the URL, or nil if it is not a scheme
      # we know about.
      #
      # @example
      #   DatabaseURL.gem_name("postgres://localhost/app")        # => "pg"
      #   DatabaseURL.gem_name("jdbc:postgresql://localhost/app") # => "jdbc-postgres"
      #
      # @param url [String, #to_s]
      #
      # @return [String, nil]
      #
      # @api private
      # @since 3.1.0
      def gem_name(url)
        gems = jdbc?(url) ? JDBC_GEMS : NATIVE_GEMS
        gems[uri(url).scheme]
      rescue URI::Error
        nil
      end
    end
  end
end
