# frozen_string_literal: true

require "uri"

module Hanami
  module DB
    # Helpers for inspecting database URLs, including the JDBC URLs required when connecting via
    # JRuby, which nest the real URL after a "jdbc:" prefix, e.g. "jdbc:postgresql://localhost/app".
    #
    # Shared by hanami and hanami-cli so that both recognise the same databases.
    #
    # @api private
    module DatabaseURL
      # Prefix of the JDBC URLs that JRuby applications must use
      JDBC_PREFIX = "jdbc:"

      # Maps URL schemes to the database adapters we support
      ADAPTERS = {
        "sqlite" => :sqlite,
        "postgres" => :postgres,
        "postgresql" => :postgres,
        "mysql" => :mysql,
        "mysql2" => :mysql
      }.freeze

      # Gems required to connect via each URL scheme. Only schemes generated by `hanami new` are
      # included: others (such as Sequel's "mysql" scheme, which uses the mysql gem rather than
      # mysql2) are left alone.
      NATIVE_GEMS = {
        "sqlite" => "sqlite3",
        "postgres" => "pg",
        "postgresql" => "pg",
        "mysql2" => "mysql2"
      }.freeze

      # Gems required to connect via each JDBC subprotocol
      JDBC_GEMS = {
        "sqlite" => "jdbc-sqlite3",
        "postgresql" => "jdbc-postgres",
        "mysql" => "jdbc-mysql"
      }.freeze

      # Adapters for each JDBC subprotocol. JDBC drivers accept only these subprotocols, e.g.
      # "postgresql" but not "postgres".
      JDBC_ADAPTERS = ADAPTERS.slice(*JDBC_GEMS.keys).freeze

      # Matches a URL's scheme, including any JDBC subprotocol, e.g. "jdbc:sqlserver". Other schemes
      # must be followed by "://", so that the username in a URL missing its scheme, such as
      # "admin:secret@localhost/app", is not mistaken for one.
      SCHEME_MATCHER = %r{\A(?:jdbc:[a-z][a-z0-9+.-]*(?=:)|[a-z][a-z0-9+.-]*(?=://))}i

      module_function

      # Returns true if the URL is a JDBC URL.
      #
      # @param url [String, #to_s]
      #
      # @return [Boolean]
      def jdbc?(url)
        url.to_s.start_with?(JDBC_PREFIX)
      end

      # Returns the URL's scheme, including any JDBC subprotocol, or nil if it has none.
      #
      # Unlike parsing the URL, this cannot fail, and never exposes the credentials the URL may
      # contain, so it is safe to use in error messages.
      #
      # @example
      #   DatabaseURL.scheme("postgres://user:pass@localhost/app") # => "postgres"
      #   DatabaseURL.scheme("jdbc:sqlserver://localhost")          # => "jdbc:sqlserver"
      #
      # @param url [String, #to_s]
      #
      # @return [String, nil]
      def scheme(url)
        url.to_s[SCHEME_MATCHER]
      end

      # Returns the URL parsed as a URI, with any JDBC prefix removed.
      #
      # @param url [String, #to_s]
      #
      # @return [URI::Generic]
      #
      # @raise [InvalidURLError] if the URL cannot be parsed
      def uri(url)
        URI(url.to_s.delete_prefix(JDBC_PREFIX))
      rescue URI::Error
        # Without a cause, since the URI error's message includes the URL and its credentials
        raise InvalidURLError.new(scheme(url)), cause: nil
      end

      # Returns the adapter for the URL, or nil if it is not one we support.
      #
      # @example
      #   DatabaseURL.adapter("postgresql://localhost/app") # => :postgres
      #   DatabaseURL.adapter("jdbc:sqlite:db/app.sqlite3") # => :sqlite
      #
      # @param url [String, #to_s]
      #
      # @return [Symbol, nil] :sqlite, :postgres or :mysql
      def adapter(url)
        adapter!(url)
      rescue InvalidURLError, UnsupportedSchemeError
        nil
      end

      # Returns the adapter for the URL, raising an error if it is not one we support.
      #
      # @example
      #   DatabaseURL.adapter!("postgresql://localhost/app") # => :postgres
      #   DatabaseURL.adapter!("oracle://localhost/app")     # raises UnsupportedSchemeError
      #
      # @param url [String, #to_s]
      #
      # @return [Symbol] :sqlite, :postgres, or :mysql
      #
      # @raise [InvalidURLError] if the URL cannot be parsed
      # @raise [UnsupportedSchemeError] if the URL's scheme is not one we support
      def adapter!(url)
        adapters = jdbc?(url) ? JDBC_ADAPTERS : ADAPTERS
        adapters.fetch(uri(url).scheme) { raise UnsupportedSchemeError.new(scheme(url)) }
      end

      # Returns the name of the gem required to connect to the URL, or nil if it is not a scheme
      # we know about.
      #
      # @example
      #   DatabaseURL.gem_name("postgres://localhost/app")        # => "pg"
      #   DatabaseURL.gem_name("jdbc:postgresql://localhost/app") # => "jdbc-postgres"
      #
      # @param url [String, #to_s]
      #
      # @return [String, nil]
      def gem_name(url)
        gems = jdbc?(url) ? JDBC_GEMS : NATIVE_GEMS
        gems[uri(url).scheme]
      rescue InvalidURLError
        nil
      end
    end
  end
end
